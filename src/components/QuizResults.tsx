import React, { useEffect, useState } from 'react';
import confetti from 'canvas-confetti';
import {
  Award,
  CheckCircle2,
  XCircle,
  AlertCircle,
  RotateCcw,
  Download,
  Printer,
  ChevronDown,
  ChevronUp,
  FileText,
  Lightbulb,
  Share2,
  ArrowRight
} from 'lucide-react';
import { QuizData, QuizEvaluationResult, QuizQuestion } from '../types/quiz';

interface QuizResultsProps {
  quiz: QuizData;
  userAnswers: Record<string, string | string[]>;
  timeSpentSeconds: number;
  onRetakeAll: () => void;
  onRetryIncorrect: (incorrectQuestions: QuizQuestion[]) => void;
  onNewQuiz: () => void;
}

export const QuizResults: React.FC<QuizResultsProps> = ({
  quiz,
  userAnswers,
  timeSpentSeconds,
  onRetakeAll,
  onRetryIncorrect,
  onNewQuiz,
}) => {
  const [filterTopic, setFilterTopic] = useState<string>('all');
  const [filterStatus, setFilterStatus] = useState<'all' | 'correct' | 'incorrect' | 'unanswered'>('all');
  const [expandedQuestions, setExpandedQuestions] = useState<Record<string, boolean>>({});

  // Compute evaluation stats
  const totalQuestions = quiz.questions.length;
  let correctCount = 0;
  let incorrectCount = 0;
  let unansweredCount = 0;
  const incorrectQuestionsList: QuizQuestion[] = [];
  const topicStats: Record<string, { total: number; correct: number }> = {};

  quiz.questions.forEach((q) => {
    const userAnswer = userAnswers[q.id];
    const topic = q.topic || 'General Material';

    if (!topicStats[topic]) {
      topicStats[topic] = { total: 0, correct: 0 };
    }
    topicStats[topic].total++;

    const isAnswered = Array.isArray(userAnswer) ? userAnswer.length > 0 : Boolean(userAnswer);

    if (!isAnswered) {
      unansweredCount++;
      incorrectQuestionsList.push(q);
      return;
    }

    let isCorrect = false;
    if (q.type === 'multi_select') {
      const correctArr = Array.isArray(q.correctAnswer) ? q.correctAnswer : [q.correctAnswer];
      const userArr = (userAnswer as string[]) || [];
      isCorrect =
        correctArr.length === userArr.length &&
        correctArr.every((item) => userArr.includes(item));
    } else {
      isCorrect = String(userAnswer).trim().toLowerCase() === String(q.correctAnswer).trim().toLowerCase();
    }

    if (isCorrect) {
      correctCount++;
      topicStats[topic].correct++;
    } else {
      incorrectCount++;
      incorrectQuestionsList.push(q);
    }
  });

  // Calculate score with negative marking if configured
  const penalty = quiz.config.negativeMarking ? 0.25 : 0;
  const rawScore = Math.max(0, correctCount - (incorrectCount * penalty));
  const maxScore = totalQuestions;
  const percentage = Math.round((correctCount / maxScore) * 100);

  // Determine Letter Grade
  let grade = 'F';
  if (percentage >= 90) grade = 'A+';
  else if (percentage >= 80) grade = 'A';
  else if (percentage >= 70) grade = 'B';
  else if (percentage >= 60) grade = 'C';
  else if (percentage >= 50) grade = 'D';

  // Trigger celebration confetti for high achievement
  useEffect(() => {
    if (percentage >= 75) {
      try {
        confetti({
          particleCount: 80,
          spread: 70,
          origin: { y: 0.6 },
          colors: ['#4f46e5', '#818cf8', '#10b981', '#f59e0b'],
        });
      } catch {
        // Safe fallback
      }
    }
  }, [percentage]);

  const toggleExpand = (id: string) => {
    setExpandedQuestions((prev) => ({ ...prev, [id]: !prev[id] }));
  };

  const expandAll = () => {
    const all: Record<string, boolean> = {};
    quiz.questions.forEach((q) => {
      all[q.id] = true;
    });
    setExpandedQuestions(all);
  };

  const collapseAll = () => {
    setExpandedQuestions({});
  };

  // Format time
  const formatTimeSpent = (sec: number) => {
    const mins = Math.floor(sec / 60);
    const secs = sec % 60;
    return `${mins}m ${secs}s`;
  };

  // Export as Markdown study summary
  const handleExportMarkdown = () => {
    let md = `# ${quiz.title} - Assessment Report\n\n`;
    md += `**Score:** ${percentage}% (${correctCount}/${totalQuestions} Correct)\n`;
    md += `**Grade:** ${grade} | **Time Spent:** ${formatTimeSpent(timeSpentSeconds)}\n`;
    md += `**Generated By:** Quizora AI\n\n`;
    md += `## Question-by-Question Review\n\n`;

    quiz.questions.forEach((q, idx) => {
      const uAns = userAnswers[q.id];
      md += `### ${idx + 1}. ${q.question}\n\n`;
      md += `- **Your Answer:** ${Array.isArray(uAns) ? uAns.join(', ') : uAns || '[Unanswered]'}\n`;
      md += `- **Correct Answer:** ${Array.isArray(q.correctAnswer) ? q.correctAnswer.join(', ') : q.correctAnswer}\n`;
      md += `- **Explanation:** ${q.explanation}\n`;
      if (q.sourcePassage) {
        md += `- **Source Citation:** *${q.sourcePassage}*\n`;
      }
      md += `\n---\n\n`;
    });

    const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${quiz.title.toLowerCase().replace(/[^a-z0-9]/g, '_')}_results.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  // Export questions as JSON
  const handleExportJson = () => {
    const payload = {
      quizTitle: quiz.title,
      score: { percentage, correctCount, totalQuestions, grade },
      questions: quiz.questions.map((q) => ({
        ...q,
        userAnswer: userAnswers[q.id] || null,
      })),
    };
    const blob = new Blob([JSON.stringify(payload, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${quiz.title.toLowerCase().replace(/[^a-z0-9]/g, '_')}_data.json`;
    link.click();
    URL.revokeObjectURL(url);
  };

  // Print results
  const handlePrint = () => {
    expandAll();
    setTimeout(() => {
      window.print();
    }, 150);
  };

  // Filtered questions
  const filteredQuestions = quiz.questions.filter((q) => {
    if (filterTopic !== 'all' && (q.topic || 'General Material') !== filterTopic) {
      return false;
    }

    const uAns = userAnswers[q.id];
    const isAnswered = Array.isArray(uAns) ? uAns.length > 0 : Boolean(uAns);

    if (filterStatus === 'unanswered') return !isAnswered;

    let isCorrect = false;
    if (q.type === 'multi_select') {
      const correctArr = Array.isArray(q.correctAnswer) ? q.correctAnswer : [q.correctAnswer];
      const userArr = (uAns as string[]) || [];
      isCorrect = correctArr.length === userArr.length && correctArr.every((item) => userArr.includes(item));
    } else {
      isCorrect = String(uAns).trim().toLowerCase() === String(q.correctAnswer).trim().toLowerCase();
    }

    if (filterStatus === 'correct') return isAnswered && isCorrect;
    if (filterStatus === 'incorrect') return isAnswered && !isCorrect;

    return true;
  });

  return (
    <div className="max-w-5xl mx-auto px-4 sm:px-6 py-8 sm:py-12 space-y-8 print:p-0">
      {/* Score Summary Card */}
      <div className="bg-white rounded-3xl border border-slate-200/90 shadow-sm p-6 sm:p-10 relative overflow-hidden">
        <div className="flex flex-col md:flex-row items-center justify-between gap-8 pb-8 border-b border-slate-100">
          <div className="text-center md:text-left space-y-2">
            <div className="text-xs font-semibold text-indigo-700 uppercase tracking-wider">
              Assessment Performance Report
            </div>
            <h2 className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight">
              {quiz.title}
            </h2>
            <p className="text-xs text-slate-500">
              Completed in {formatTimeSpent(timeSpentSeconds)} · {quiz.config.mode.toUpperCase()} MODE
            </p>
          </div>

          <div className="flex items-center gap-6">
            <div className="text-center">
              <div className="text-5xl sm:text-6xl font-black text-indigo-600 font-mono tracking-tight tabular-nums">
                {percentage}%
              </div>
              <div className="text-xs font-semibold text-slate-500 uppercase mt-1">Accuracy</div>
            </div>

            <div className="w-16 h-16 sm:w-20 sm:h-20 rounded-2xl bg-indigo-50 border border-indigo-100 flex flex-col items-center justify-center text-indigo-900 font-extrabold shadow-2xs">
              <span className="text-2xl sm:text-3xl font-black">{grade}</span>
              <span className="text-[10px] text-indigo-600 uppercase font-bold">Grade</span>
            </div>
          </div>
        </div>

        {/* 4 Quantitative Breakdown KPI Metrics */}
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 py-6 border-b border-slate-100 text-center">
          <div className="p-3.5 rounded-2xl bg-slate-50 border border-slate-100">
            <div className="text-2xl font-bold text-slate-900 font-mono tabular-nums">{totalQuestions}</div>
            <div className="text-xs text-slate-500 mt-0.5">Total Questions</div>
          </div>
          <div className="p-3.5 rounded-2xl bg-emerald-50/70 border border-emerald-100">
            <div className="text-2xl font-bold text-emerald-700 font-mono tabular-nums">{correctCount}</div>
            <div className="text-xs text-emerald-800 mt-0.5">Correct Answers</div>
          </div>
          <div className="p-3.5 rounded-2xl bg-rose-50/70 border border-rose-100">
            <div className="text-2xl font-bold text-rose-700 font-mono tabular-nums">{incorrectCount}</div>
            <div className="text-xs text-rose-800 mt-0.5">Incorrect Answers</div>
          </div>
          <div className="p-3.5 rounded-2xl bg-slate-50 border border-slate-100">
            <div className="text-2xl font-bold text-slate-600 font-mono tabular-nums">{unansweredCount}</div>
            <div className="text-xs text-slate-500 mt-0.5">Unanswered</div>
          </div>
        </div>

        {/* Action Row */}
        <div className="pt-6 flex flex-wrap items-center justify-between gap-4 print:hidden">
          <div className="flex flex-wrap items-center gap-2">
            {incorrectQuestionsList.length > 0 && (
              <button
                onClick={() => onRetryIncorrect(incorrectQuestionsList)}
                className="px-4 py-2.5 rounded-xl text-xs font-bold text-white bg-indigo-600 hover:bg-indigo-700 active:bg-indigo-800 transition-colors shadow-xs flex items-center gap-2"
              >
                <RotateCcw className="w-3.5 h-3.5" />
                <span>Retry Missed Questions ({incorrectQuestionsList.length})</span>
              </button>
            )}

            <button
              onClick={onRetakeAll}
              className="px-4 py-2.5 rounded-xl text-xs font-bold text-slate-700 bg-white border border-slate-200 hover:bg-slate-50 transition-colors flex items-center gap-2"
            >
              <RotateCcw className="w-3.5 h-3.5" />
              <span>Retake Complete Quiz</span>
            </button>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleExportMarkdown}
              className="px-3.5 py-2 rounded-xl text-xs font-medium text-slate-600 border border-slate-200 hover:bg-slate-50 transition-colors flex items-center gap-1.5"
              title="Download Study Markdown"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Export Guide</span>
            </button>
            <button
              onClick={handleExportJson}
              className="px-3.5 py-2 rounded-xl text-xs font-medium text-slate-600 border border-slate-200 hover:bg-slate-50 transition-colors flex items-center gap-1.5"
              title="Export Raw JSON"
            >
              <FileText className="w-3.5 h-3.5" />
              <span>Export JSON</span>
            </button>
            <button
              onClick={handlePrint}
              className="px-3.5 py-2 rounded-xl text-xs font-medium text-slate-600 border border-slate-200 hover:bg-slate-50 transition-colors flex items-center gap-1.5"
              title="Print Results"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>Print</span>
            </button>
            <button
              onClick={onNewQuiz}
              className="px-4 py-2 rounded-xl text-xs font-bold text-indigo-700 bg-indigo-50 hover:bg-indigo-100 transition-colors flex items-center gap-1.5"
            >
              <span>Create New Quiz</span>
              <ArrowRight className="w-3.5 h-3.5" />
            </button>
          </div>
        </div>
      </div>

      {/* Topic Breakdown Diagnostic */}
      {Object.keys(topicStats).length > 0 && (
        <div className="bg-white rounded-2xl border border-slate-200/90 shadow-sm p-6 sm:p-8 space-y-4">
          <h3 className="text-sm font-bold text-slate-900 uppercase tracking-wider">
            Diagnostic Topic Breakdown
          </h3>
          <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-3">
            {Object.entries(topicStats).map(([topic, stats]) => {
              const pct = Math.round((stats.correct / stats.total) * 100);
              return (
                <div key={topic} className="p-4 rounded-xl border border-slate-200/80 bg-slate-50/50 space-y-2">
                  <div className="flex items-center justify-between text-xs font-bold text-slate-800">
                    <span className="truncate">{topic}</span>
                    <span className="font-mono tabular-nums">{pct}%</span>
                  </div>
                  <div className="w-full h-1.5 rounded-full bg-slate-200 overflow-hidden">
                    <div
                      className={`h-full ${pct >= 70 ? 'bg-emerald-500' : pct >= 40 ? 'bg-amber-500' : 'bg-rose-500'}`}
                      style={{ width: `${pct}%` }}
                    />
                  </div>
                  <div className="text-[11px] text-slate-400">
                    {stats.correct} of {stats.total} questions answered correctly
                  </div>
                </div>
              );
            })}
          </div>
        </div>
      )}

      {/* Question-by-Question Review Section */}
      <div className="space-y-4">
        <div className="flex flex-wrap items-center justify-between gap-4 print:hidden">
          <h3 className="text-base font-bold text-slate-900">
            Question-by-Question Detailed Review
          </h3>

          <div className="flex flex-wrap items-center gap-2">
            {/* Filter buttons */}
            <div className="flex items-center gap-1 p-1 bg-slate-100 rounded-xl text-xs">
              {(['all', 'correct', 'incorrect', 'unanswered'] as const).map((status) => (
                <button
                  key={status}
                  onClick={() => setFilterStatus(status)}
                  className={`px-3 py-1 font-semibold rounded-lg capitalize transition-colors ${
                    filterStatus === status ? 'bg-white text-slate-900 shadow-2xs' : 'text-slate-500 hover:text-slate-900'
                  }`}
                >
                  {status}
                </button>
              ))}
            </div>

            <button
              onClick={expandAll}
              className="px-2.5 py-1 text-xs text-slate-500 hover:text-slate-800"
            >
              Expand All
            </button>
            <button
              onClick={collapseAll}
              className="px-2.5 py-1 text-xs text-slate-500 hover:text-slate-800"
            >
              Collapse All
            </button>
          </div>
        </div>

        {/* Questions list */}
        <div className="space-y-4">
          {filteredQuestions.map((q, index) => {
            const userAnswer = userAnswers[q.id];
            const isAnswered = Array.isArray(userAnswer) ? userAnswer.length > 0 : Boolean(userAnswer);

            let isCorrect = false;
            if (q.type === 'multi_select') {
              const correctArr = Array.isArray(q.correctAnswer) ? q.correctAnswer : [q.correctAnswer];
              const userArr = (userAnswer as string[]) || [];
              isCorrect = correctArr.length === userArr.length && correctArr.every((item) => userArr.includes(item));
            } else {
              isCorrect = String(userAnswer).trim().toLowerCase() === String(q.correctAnswer).trim().toLowerCase();
            }

            const isExpanded = expandedQuestions[q.id] !== false; // Default expanded

            return (
              <div
                key={q.id}
                className={`rounded-2xl border bg-white shadow-2xs overflow-hidden transition-all ${
                  !isAnswered
                    ? 'border-slate-300'
                    : isCorrect
                    ? 'border-emerald-200'
                    : 'border-rose-200'
                }`}
              >
                {/* Question Header Card */}
                <div
                  onClick={() => toggleExpand(q.id)}
                  className="p-5 flex items-start justify-between gap-4 cursor-pointer hover:bg-slate-50/50 transition-colors"
                >
                  <div className="flex items-start gap-3">
                    <div className="mt-0.5">
                      {!isAnswered ? (
                        <AlertCircle className="w-5 h-5 text-slate-400" />
                      ) : isCorrect ? (
                        <CheckCircle2 className="w-5 h-5 text-emerald-600" />
                      ) : (
                        <XCircle className="w-5 h-5 text-rose-500" />
                      )}
                    </div>
                    <div>
                      <div className="flex items-center gap-2 text-xs text-slate-400 font-medium mb-1">
                        <span>Question {index + 1}</span>
                        <span>·</span>
                        <span className="capitalize">{q.type.replace('_', ' ')}</span>
                        {q.topic && (
                          <>
                            <span>·</span>
                            <span>{q.topic}</span>
                          </>
                        )}
                        <span>·</span>
                        <span
                          className={`font-semibold ${
                            !isAnswered
                              ? 'text-slate-500'
                              : isCorrect
                              ? 'text-emerald-700'
                              : 'text-rose-700'
                          }`}
                        >
                          {!isAnswered ? 'Unanswered' : isCorrect ? 'Correct (+1)' : 'Incorrect'}
                        </span>
                      </div>
                      <h4 className="text-sm sm:text-base font-semibold text-slate-900 leading-snug">
                        {q.question}
                      </h4>
                    </div>
                  </div>

                  <button className="text-slate-400 p-1">
                    {isExpanded ? <ChevronUp className="w-4 h-4" /> : <ChevronDown className="w-4 h-4" />}
                  </button>
                </div>

                {/* Expanded Details */}
                {isExpanded && (
                  <div className="px-5 pb-5 pt-2 border-t border-slate-100 space-y-4 text-xs sm:text-sm">
                    {/* Options list */}
                    <div className="space-y-2">
                      {q.options.map((opt, oIdx) => {
                        const letter = String.fromCharCode(65 + oIdx);
                        const isUserChoice =
                          q.type === 'multi_select'
                            ? Array.isArray(userAnswer) && userAnswer.includes(opt)
                            : userAnswer === opt;

                        const isCorrectChoice =
                          q.type === 'multi_select'
                            ? Array.isArray(q.correctAnswer) && q.correctAnswer.includes(opt)
                            : String(q.correctAnswer).trim().toLowerCase() === opt.trim().toLowerCase();

                        let rowStyle = 'bg-slate-50/60 border-slate-200 text-slate-700';

                        if (isCorrectChoice) {
                          rowStyle = 'bg-emerald-50/80 border-emerald-300 text-emerald-950 font-medium';
                        } else if (isUserChoice && !isCorrectChoice) {
                          rowStyle = 'bg-rose-50/70 border-rose-300 text-rose-950';
                        }

                        return (
                          <div
                            key={oIdx}
                            className={`p-3 rounded-xl border flex items-center justify-between gap-3 ${rowStyle}`}
                          >
                            <div className="flex items-center gap-2.5">
                              <span className="w-6 h-6 rounded-md bg-white border border-slate-200 text-xs font-bold flex items-center justify-center shrink-0">
                                {letter}
                              </span>
                              <span className="leading-relaxed">{opt}</span>
                            </div>
                            <div className="flex items-center gap-2 shrink-0 text-xs font-semibold">
                              {isCorrectChoice && (
                                <span className="text-emerald-700 flex items-center gap-1">
                                  <CheckCircle2 className="w-4 h-4" /> Correct Answer
                                </span>
                              )}
                              {isUserChoice && !isCorrectChoice && (
                                <span className="text-rose-700 flex items-center gap-1">
                                  <XCircle className="w-4 h-4" /> Your Choice
                                </span>
                              )}
                            </div>
                          </div>
                        );
                      })}
                    </div>

                    {/* Educational Explanation Box */}
                    <div className="p-4 rounded-xl bg-indigo-50/40 border border-indigo-100/80 space-y-2">
                      <div className="flex items-center gap-1.5 text-xs font-bold text-indigo-900">
                        <Lightbulb className="w-4 h-4 text-indigo-600" />
                        <span>Educational Explanation</span>
                      </div>
                      <p className="text-slate-700 leading-relaxed text-xs sm:text-sm">
                        {q.explanation}
                      </p>
                      {q.sourcePassage && (
                        <div className="pt-2 border-t border-indigo-100 text-xs text-slate-500">
                          <span className="font-semibold text-slate-700">Source Material Reference: </span>
                          <span className="italic">{q.sourcePassage}</span>
                        </div>
                      )}
                    </div>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
};
